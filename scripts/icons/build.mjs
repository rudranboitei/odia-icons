// Build icons.json, the typed icon manifest, raw SVGs, a sprite and
// shadcn-style registry files from icons/ + meta/.
// Run with: bun run icons:build
import { mkdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { loadIcons, ROOT, VARIANTS } from "./validate.mjs"

const OUT = {
  generated: path.join(ROOT, "src/lib/icons.generated.ts"),
  manifest: path.join(ROOT, "public/icons.json"),
  svg: path.join(ROOT, "public/svg"),
  registry: path.join(ROOT, "public/r"),
  sprite: path.join(ROOT, "public/odiaicons-sprite.svg"),
}

const titleOf = (name) =>
  name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")

const strokeOf = (icon) => Number(icon.variants.outline?.stroke ?? 1.5)

function generatedTypes() {
  return `// Generated by \`bun run icons:build\` from icons/ and meta/. Do not edit by hand.

export type IconCategory =
  | "culture"
  | "architecture"
  | "art"
  | "festival"
  | "food"
  | "nature"
  | "travel"
  | "ui"

export type IconVariant = "outline" | "solid" | "duotone"

export type IconDef = {
  name: string
  odia: string
  category: IconCategory
  tags: string[]
  aliases: string[]
  variants: IconVariant[]
  contributors: string[]
  since: string
  note: string
  /** Stroke width this icon was drawn with (new icons 1.5, old ones 1.75). */
  strokeWidth: number
  /** Inner SVG markup for the outline variant, drawn on a 24×24 grid. */
  body: string
}
`
}

function generatedModule(icons) {
  const entries = icons
    .map((icon) => {
      const body = icon.variants.outline?.body ?? ""
      return `  {
    name: ${JSON.stringify(icon.name)},
    odia: ${JSON.stringify(icon.odia)},
    category: ${JSON.stringify(icon.category)},
    tags: ${JSON.stringify(icon.tags)},
    aliases: ${JSON.stringify(icon.aliases)},
    variants: ${JSON.stringify(icon.variantsList)},
    contributors: ${JSON.stringify(icon.contributors)},
    since: ${JSON.stringify(icon.since)},
    note: ${JSON.stringify(icon.note)},
    strokeWidth: ${strokeOf(icon)},
    body: ${JSON.stringify(body)},
  },`
    })
    .join("\n")

  return `${generatedTypes()}
export const icons: IconDef[] = [
${entries}
]

/** Icons keyed by every accepted name and alias. */
export const iconsByName: Record<string, IconDef> = Object.fromEntries(
  icons.flatMap((icon) => [icon.name, ...icon.aliases].map((key) => [key, icon]))
)

export const iconCategories = [...new Set(icons.map((icon) => icon.category))]
`
}

function sprite(icons) {
  const symbols = icons
    .map((icon) => {
      const body = icon.variants.outline?.body ?? ""
      return `  <symbol id="odiaicons-${icon.name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeOf(icon)}" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`
    })
    .join("\n")

  return `<svg xmlns="http://www.w3.org/2000/svg">
${symbols}
</svg>
`
}

function registryItem(icon) {
  const files = Object.entries(icon.variants).map(([variant, file]) => ({
    path: `icons/${variant}/${icon.name}.svg`,
    type: "registry:file",
    target: `components/icons/${icon.name}.svg`,
    content: file.svg.trim(),
  }))

  return {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: icon.name,
    type: "registry:ui",
    title: titleOf(icon.name),
    description: `${icon.odia} — ${icon.tags.slice(0, 3).join(", ")}.`,
    categories: [icon.category],
    meta: {
      odia: icon.odia,
      since: icon.since,
      variants: icon.variantsList,
    },
    files,
  }
}

async function main() {
  const raw = await loadIcons()
  const icons = raw.map((icon) => ({
    ...icon,
    variantsList: Object.keys(icon.variants),
  }))

  await mkdir(path.dirname(OUT.generated), { recursive: true })
  await writeFile(OUT.generated, generatedModule(icons))

  await rm(OUT.svg, { recursive: true, force: true })
  await rm(OUT.registry, { recursive: true, force: true })

  for (const variant of VARIANTS) {
    const variantIcons = icons.filter((icon) => icon.variants[variant])
    if (variantIcons.length === 0) continue
    const dir = path.join(OUT.svg, variant)
    await mkdir(dir, { recursive: true })
    for (const icon of variantIcons) {
      await writeFile(path.join(dir, `${icon.name}.svg`), `${icon.variants[variant].svg.trim()}\n`)
    }
  }

  await mkdir(OUT.registry, { recursive: true })
  for (const icon of icons) {
    await writeFile(
      path.join(OUT.registry, `${icon.name}.json`),
      `${JSON.stringify(registryItem(icon), null, 2)}\n`
    )
  }

  await writeFile(OUT.sprite, sprite(icons))

  const manifest = {
    name: "odiaicons",
    version: "0.1.0",
    grid: 24,
    strokeWidth: 1.5,
    icons: icons.map((icon) => ({
      name: icon.name,
      odia: icon.odia,
      category: icon.category,
      tags: icon.tags,
      aliases: icon.aliases,
      variants: icon.variantsList,
      since: icon.since,
      note: icon.note,
      strokeWidth: strokeOf(icon),
      body: icon.variants.outline?.body ?? "",
      files: Object.fromEntries(
        icon.variantsList.map((variant) => [variant, `/svg/${variant}/${icon.name}.svg`])
      ),
    })),
  }
  await writeFile(OUT.manifest, `${JSON.stringify(manifest, null, 2)}\n`)

  const files = icons.reduce((n, icon) => n + icon.variantsList.length, 0)
  console.log(
    `✓ Built ${icons.length} icons (${files} SVGs) → icons.generated.ts, icons.json, sprite, ${icons.length} registry items`
  )
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
